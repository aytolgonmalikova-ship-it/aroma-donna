// Помощник: строит варианты объёма из базовой цены (30 мл → 50 мл → 100 мл)
const makeVolumes = (base, sizes = [30, 50, 100]) => {
  const multipliers = { 30: 1, 50: 1.45, 75: 1.85, 100: 2.3 };
  return sizes.map((ml) => ({
    ml,
    price: Math.round((base * multipliers[ml]) / 50) * 50,
  }));
};

